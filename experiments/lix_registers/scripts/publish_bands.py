"""Turn the measured band mapping into the literal the package ships.

Split from ``run.py`` deliberately. Measuring takes half an hour; deciding what
to publish from the measurement takes a second, and wanting to change the second
is not a reason to redo the first. This reads ``results/registers.json`` and
writes ``src/saphes/datasets/_lix_bands.py``.

**What "validated" means here, and what it does not.** The mapping is
equipercentile: for each Swedish band boundary, find the fraction of Swedish
text below it, then read the Hungarian score at that same fraction. So a
published boundary preserves *how much text falls in each band*. It does not
mean anyone has checked that Hungarian readers find those texts correspondingly
hard. Nobody has. That would need a graded corpus, and there is not one here.

A boundary is published only where the reference has enough text on **both**
sides of it to place it. That is what fails at the top of the scale, and the
numbers say so plainly: Swedish news puts about 0.04% of its windows above LIX
60, so the ``difficult`` boundary is read off one to twelve windows depending on
the window length. It is not that Hungarian is unstable up there; it is that
Swedish news has almost no text up there to map from. A corpus of harder writing
would place it; this one cannot.

Each boundary is also checked against a ladder of window lengths, and the drift
is published as a diagnostic. Support is the rule, drift is the symptom — a
boundary short of support is exactly the one whose drift is large.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

EXPERIMENT_DIR = Path(__file__).resolve().parents[1]
RESULTS = EXPERIMENT_DIR / "results" / "registers.json"
LITERAL = (
    Path(__file__).resolve().parents[3]
    / "src"
    / "saphes"
    / "datasets"
    / "_lix_bands.py"
)

# A quantile needs data on both sides of it. This is how many reference windows
# must sit on the thinner side before the boundary is publishable. At the
# publication window the three inner boundaries clear it by a factor of two or
# more, and the outermost misses it by two orders of magnitude, so the exact
# value is not load-bearing.
MIN_SUPPORT = 200

# Reported alongside, as a symptom rather than a rule: how far the boundary
# moves across the window-length ladder.
MAX_DRIFT = 1.5

# Calibration keys are language-and-policy; the mapping is computed per policy.
POLICY_TO_KEY = {"chars": "hu", "letters": "hu-letters"}


def drift(stability: dict[str, list[float]], index: int) -> float:
    """How far one boundary moves across the whole window ladder."""
    values = [row[index] for row in stability.values()]
    return max(values) - min(values)


def build(record: dict) -> dict:
    """Assemble the published band table from the measurement."""
    reference_windows = next(
        row["windows"]
        for row in record["rows"]
        if row["register"] == "leipzig-swe-news"
    )
    published = {}
    for policy, mapping in record["band_mapping"].items():
        key = POLICY_TO_KEY.get(policy)
        if key is None:  # pragma: no cover - defensive
            continue
        stability = record["band_stability"][policy]
        rows = []
        for index, row in enumerate(mapping):
            fraction = row["fraction_below"]
            support = round(min(fraction, 1.0 - fraction) * reference_windows)
            rows.append(
                {
                    **row,
                    "support": support,
                    "drift": round(drift(stability, index), 2),
                    "published": support >= MIN_SUPPORT,
                }
            )
        # Bands are an ordered scale, so resolution stops at the first boundary
        # that cannot be placed; a gap in the middle would make every label
        # above it meaningless.
        resolvable = 0
        for row in rows:
            if not row["published"]:
                break
            resolvable += 1
        published[key] = {
            "bands": rows,
            "window": record["window"],
            "reference": record["reference"],
            "reference_windows": reference_windows,
            "resolvable": resolvable,
            "max_shift": round(
                max((abs(r["shift"]) for r in rows[:resolvable]), default=0.0), 2
            ),
        }
    return published


def render(record: dict, published: dict) -> str:
    """Render the module source."""
    lines = [
        '"""Hungarian LIX interpretation bands, mapped from the Swedish ones.',
        "",
        "GENERATED by experiments/lix_registers/scripts/publish_bands.py"
        " — do not edit by hand.",
        "",
        "``LIX_BANDS`` in ``saphes.readability`` are Bjornsson's, fitted to Swedish",
        "prose at threshold 6. At a calibrated threshold a score is not on that",
        "scale, which is why ``LixResult.band`` returns ``None`` there.",
        "",
        "These are the same boundaries carried across by equipercentile mapping:",
        "for each Swedish boundary, the Hungarian score below which the same share",
        "of running text falls. They preserve how much text lands in each band.",
        "**They do not encode any judgement about how hard Hungarian readers find",
        "those texts** — that would need a graded corpus, and no such corpus was",
        "used here.",
        "",
        "The full measurement, including the window-length ladder each boundary was",
        "checked against, is in experiments/lix_registers/results/registers.json.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        f"GENERATED = {record['generated']!r}",
        "SCHEMA_VERSION = 1",
        "",
        "BANDS: dict[str, dict[str, Any]] = {",
    ]
    for key, entry in published.items():
        lines += [
            f"    {key!r}: {{",
            f'        "window": {entry["window"]},',
            f'        "reference": {entry["reference"]!r},',
            f'        "reference_windows": {entry["reference_windows"]},',
            f'        "resolvable": {entry["resolvable"]},',
            f'        "max_shift": {entry["max_shift"]!r},',
            "        # (mapped boundary, label, Swedish boundary, drift, support)",
            "        # Only the first `resolvable` entries are usable; the rest",
            "        # are recorded so the reason for stopping is auditable.",
            '        "bands": (',
        ]
        for row in entry["bands"]:
            lines.append(
                f"            ({row['mapped_boundary']!r}, {row['band']!r}, "
                f"{row['swedish_boundary']!r}, {row['drift']!r}, {row['support']}),"
            )
        lines += ["        ),", "    },"]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    """Read the measurement, write the literal, format it."""
    if not RESULTS.exists():
        print(f"missing {RESULTS}; run run.py first", file=sys.stderr)
        raise SystemExit(1)
    record = json.loads(RESULTS.read_text())
    published = build(record)

    for key, entry in published.items():
        print(
            f"{key:<11} {entry['resolvable']} of {len(entry['bands'])} boundaries "
            f"placed, max shift {entry['max_shift']:+.2f}"
        )
        for row in entry["bands"]:
            flag = "ok" if row["published"] else "NO SUPPORT"
            print(
                f"    {row['band']:<15} {row['swedish_boundary']:>5.0f} -> "
                f"{row['mapped_boundary']:>6.2f}  (shift {row['shift']:+.2f}, "
                f"drift {row['drift']:.2f}, support {row['support']:>5,}) {flag}"
            )

    LITERAL.write_text(render(record, published))
    subprocess.run(  # noqa: S603
        ["uv", "run", "ruff", "format", "--quiet", str(LITERAL)],  # noqa: S607
        check=False,
        capture_output=True,
    )
    print(f"\nwrote {LITERAL} ({LITERAL.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
